# Step 1: Import libraries

import pandas as pd
import matplotlib.pyplot as plt
from sklearn.tree import DecisionTreeClassifier


# Step 2: Create the dataset

data = {
    "weight": [150, 170, 160, 180, 200, 190],
    "diameter": [7.0, 7.5, 7.2, 7.0, 7.5, 7.2],
    "fruit": ["Apple", "Apple", "Apple",
              "Orange", "Orange", "Orange"]
} # weight = gm , diameter = cm

# input/feature, output/result, label
# Step 3: Convert the dataset into a DataFrame

df = pd.DataFrame(data)

print("Our Dataset:")
print(df)


# Step 4: Visualize the dataset

for fruit in df["fruit"].unique(): # apple, orange.
    fruit_data = df[df["fruit"] == fruit] # apple, organe, banana

    plt.scatter(
        fruit_data["weight"],
        fruit_data["diameter"],
        label=fruit
    )

plt.xlabel("Weight (grams)")
plt.ylabel("Diameter (cm)")
plt.title("Binary Fruit Classification")
plt.legend()
plt.grid(True)
plt.show()


# Step 5: Select input features

X = df[["weight", "diameter"]] #inputs


# Step 6: Select target variable

y = df["fruit"] # output


# Step 7: Create the model

model = DecisionTreeClassifier() #


# Step 8: Train the model

model.fit(X, y)


# Step 9: Give the model a new fruit to classify

new_fruit = pd.DataFrame({
    "weight": [125],
    "diameter": [3.2]
})


# Step 10: Make a prediction

prediction = model.predict(new_fruit)


# Step 11: Display the prediction

print("Predicted fruit:", prediction[0])

